@app.post("/api/auth/signup")
def customer_signup():
    data = request.get_json(silent=True) or {}

    if not isinstance(data, dict):
        return jsonify({
            "error": "Invalid request."
        }), 400

    name = str(data.get("name", "")).strip()
    phone = str(data.get("phone", "")).strip()
    email = str(data.get("email", "")).strip().lower()
    password = data.get("password", "")

    if (
        not name
        or len(name) > 100
        or not re.fullmatch(r"[0-9+() -]{8,20}", phone)
    ):
        return jsonify({
            "error": "Enter a valid name and phone number."
        }), 400

    if (
        len(email) > 254
        or not re.fullmatch(
            r"[^\s@]+@[^\s@]+\.[^\s@]+",
            email
        )
    ):
        return jsonify({
            "error": "Enter a valid email address."
        }), 400

    if (
        not isinstance(password, str)
        or not (8 <= len(password) <= 128)
    ):
        return jsonify({
            "error": "Password must be 8 to 128 characters."
        }), 400

    try:
        with db() as con:
            cursor = con.execute(
                """
                INSERT INTO customers(
                    name, phone, email, password_hash
                )
                VALUES(?,?,?,?)
                RETURNING id
                """,
                (
                    name,
                    phone,
                    email,
                    generate_password_hash(password)
                )
            )

            customer_id = cursor.fetchone()["id"]
            customer = con.execute(
                "SELECT * FROM customers WHERE id=?",
                (customer_id,)
            ).fetchone()

            token = create_customer_token(
                con,
                customer["id"]
            )

    except (sqlite3.IntegrityError, psycopg.IntegrityError):
        return jsonify({
            "error": "An account with this email already exists."
        }), 409

    return jsonify({
        "message": "Account created",
        "customer": customer_public(customer),
        "token": token
    }), 201


