@app.post("/api/orders")
def create_order():
    data = request.get_json(silent=True) or {}

    name = str(
        data.get("customer_name", "")
    ).strip()

    phone = str(
        data.get("phone", "")
    ).strip()

    address = str(
        data.get("address", "")
    ).strip()

    items = data.get("items", [])

    if (
        not name
        or not phone
        or not address
        or not isinstance(items, list)
        or not items
    ):
        return jsonify({
            "error": (
                "Name, phone, address and at least "
                "one item are required."
            )
        }), 400

    if len(phone) < 8 or len(phone) > 16:
        return jsonify({
            "error": "Please enter a valid phone number."
        }), 400

    try:
        with db() as con:
            customer = authenticated_customer(con)

            if customer is None:
                return jsonify({
                    "error": "Please log in to place an order."
                }), 401

            total = 0.0
            validated = []

            for item in items:
                pid = int(item.get("product_id"))
                qty = int(item.get("quantity", 1))

                if qty < 1 or qty > 100:
                    return jsonify({
                        "error": "Quantity must be between 1 and 100."
                    }), 400

                p = con.execute(
                    """
                    SELECT id, name, price, stock
                    FROM products
                    WHERE id=? AND active=1
                    """,
                    (pid,)
                ).fetchone()

                if not p:
                    return jsonify({
                        "error": f"Product {pid} is unavailable."
                    }), 400

                if p["stock"] < qty:
                    return jsonify({
                        "error": f"Not enough stock for {p['name']}."
                    }), 400

                total += float(p["price"]) * qty
                validated.append((p, qty))

            cur = con.execute(
                """
                INSERT INTO orders(
                    customer_name,
                    phone,
                    address,
                    total,
                    payment_method,
                    status,
                    customer_id
                )
                VALUES(?,?,?,?,?,?,?)
                RETURNING id
                """,
                (
                    name,
                    phone,
                    address,
                    round(total, 2),
                    "Cash on Delivery",
                    "Order Placed",
                    customer["id"]
                )
            )

            order_id = cur.fetchone()["id"]

            for p, qty in validated:
                con.execute(
                    """
                    INSERT INTO order_items(
                        order_id,
                        product_id,
                        product_name,
                        price,
                        quantity
                    )
                    VALUES(?,?,?,?,?)
                    """,
                    (
                        order_id,
                        p["id"],
                        p["name"],
                        p["price"],
                        qty
                    )
                )

                con.execute(
                    """
                    UPDATE products
                    SET stock=stock-?
                    WHERE id=?
                    """,
                    (qty, p["id"])
                )

        return jsonify({
            "message": "Order placed",
            "order_id": order_id,
            "total": round(total, 2)
        }), 201

    except (TypeError, ValueError):
        return jsonify({
            "error": "Invalid item data."
        }), 400


