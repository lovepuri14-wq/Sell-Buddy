def customer_public(row):
    return {
        "id": row["id"],
        "name": row["name"],
        "phone": row["phone"],
        "email": row["email"]
    }


def create_customer_token(con, customer_id):
    token = secrets.token_urlsafe(32)

    digest = hashlib.sha256(
        token.encode("utf-8")
    ).hexdigest()

    expires = (
        datetime.now(timezone.utc) + timedelta(days=7)
    ).isoformat()

    con.execute(
        """
        INSERT INTO customer_sessions(
            token_hash, customer_id, expires_at
        )
        VALUES(?,?,?)
        """,
        (digest, customer_id, expires)
    )

    return token


def authenticated_customer(con):
    header = request.headers.get("Authorization", "")

    if not header.startswith("Bearer "):
        return None

    token = header[7:].strip()

    if not token:
        return None

    digest = hashlib.sha256(
        token.encode("utf-8")
    ).hexdigest()

    row = con.execute(
        """
        SELECT c.*, s.expires_at
        FROM customers c
        JOIN customer_sessions s
            ON s.customer_id = c.id
        WHERE s.token_hash = ?
        """,
        (digest,)
    ).fetchone()

    if not row:
        return None

    if datetime.fromisoformat(
        row["expires_at"]
    ) <= datetime.now(timezone.utc):

        con.execute(
            "DELETE FROM customer_sessions WHERE token_hash=?",
            (digest,)
        )

        return None

    return row


