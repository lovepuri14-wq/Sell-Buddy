@app.get("/api/orders/<int:order_id>")
def order_status(order_id):
    with db() as con:
        order = con.execute(
            """
            SELECT id, status, total, created_at
            FROM orders
            WHERE id=?
            """,
            (order_id,)
        ).fetchone()

        if not order:
            return jsonify({
                "error": "Order not found"
            }), 404

        items = con.execute(
            """
            SELECT product_name, price, quantity
            FROM order_items
            WHERE order_id=?
            """,
            (order_id,)
        ).fetchall()

    result = dict(order)
    result["items"] = [
        dict(x) for x in items
    ]

    return jsonify(result)


